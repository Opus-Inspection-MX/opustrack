export type WorkflowActor = {
  id: string;
  name: string;
  email: string;
  password: string;
};
export type WorkflowRole =
  | "employee"
  | "otherEmployee"
  | "vacationAdmin"
  | "operations"
  | "reporter"
  | "candidateA"
  | "fsrB"
  | "fsrC";
type CalendarRule = Pick<
  Holiday,
  "month" | "day" | "nthMonday" | "isRecurring" | "year" | "active"
>;

/** Civil arithmetic uses UTC only as a calendar carrier, never as app time. */
export function addCivilDays(day: string, count: number): string {
  const date = new Date(`${day}T00:00:00Z`);
  date.setUTCDate(date.getUTCDate() + count);
  return date.toISOString().slice(0, 10);
}

export function holidayMatches(day: string, rule: CalendarRule): boolean {
  const date = new Date(`${day}T00:00:00Z`);
  if (!rule.active || date.getUTCMonth() + 1 !== rule.month) return false;
  if (!rule.isRecurring && date.getUTCFullYear() !== rule.year) return false;
  return rule.day != null
    ? date.getUTCDate() === rule.day
    : date.getUTCDay() === 1 &&
        Math.ceil(date.getUTCDate() / 7) === rule.nthMonday;
}

export function chargeableRange(
  start: string,
  days: number,
  holidays: CalendarRule[] = [],
) {
  if (!Number.isInteger(days) || days < 1)
    throw new Error("A workflow range needs at least one chargeable day.");
  const chargedDates: string[] = [];
  let end = start;
  for (let offset = 0; chargedDates.length < days; offset += 1) {
    if (offset > 730)
      throw new Error("Workflow calendar has no usable chargeable range.");
    end = addCivilDays(start, offset);
    if (
      new Date(`${end}T00:00:00Z`).getUTCDay() !== 0 &&
      !holidays.some((rule) => holidayMatches(end, rule))
    )
      chargedDates.push(end);
  }
  return { start, end, chargedDates };
}

export type WorkflowWorld = {
  namespace: string;
  today: string;
  actors: Record<WorkflowRole, WorkflowActor>;
  client: { id: string; code: string; name: string };
  line: { id: number; name: string };
  equipment: { id: number; name: string };
  vehicles: { id: string; licensePlate: string }[];
  holidays: CalendarRule[];
  range: (offset: number, days: number) => ReturnType<typeof chargeableRange>;
  assertSameDay: () => void;
};

const roleCodes: Record<WorkflowRole, string> = {
  employee: "EMPLEADO",
  otherEmployee: "EMPLEADO",
  vacationAdmin: "ADMIN_VACACIONES",
  operations: "ADMIN_OPERACION",
  reporter: "REPORTER",
  candidateA: "FSR",
  fsrB: "FSR",
  fsrC: "FSR",
};

export const test = base.extend<{ world: WorkflowWorld }>({
  world: async ({ browserName }, use, info) => {
    if (browserName !== "chromium")
      throw new Error(
        "Workflow acceptance uses the dedicated Chromium project.",
      );
    if (process.env.E2E_WORKFLOWS !== "1" || info.project.name !== "workflows")
      throw new Error(
        "Workflow fixtures require the isolated workflows project.",
      );
    if (
      process.env.E2E_SEED_SCRIPT &&
      process.env.E2E_SEED_SCRIPT !== "initial_load/seed.example.ts"
    )
      throw new Error(
        "Workflow acceptance requires the tracked synthetic seed.",
      );
    assertEphemeralDatabase(process.env.DATABASE_URL);
    const prisma = db();
    const namespace = `wf-${info.retry}-${randomUUID().slice(0, 8)}`;
    const today = mxDateString(new Date());
    const holidays = await prisma.holiday.findMany();
    const matching = holidays.filter((rule) => holidayMatches(today, rule));
    const setting = await prisma.vacationSetting.findUniqueOrThrow({
      where: { id: 1 },
    });
    let world: WorkflowWorld | undefined;
    try {
      world = await prisma.$transaction(
        async (tx) => {
          // Prerequisites only. Periods are generated by the application's UI reads.
          await tx.vacationSetting.update({
            where: { id: 1 },
            data: { graceWindowMonths: 24 },
          });
          await tx.holiday.updateMany({
            where: { id: { in: matching.map((row) => row.id) } },
            data: { active: false },
          });
          const state = await tx.state.findFirstOrThrow({
            where: { active: true },
          });
          const userStatus = await tx.userStatus.findFirstOrThrow({
            where: { code: "ACTIVO", active: true },
          });
          const vehicleStatus = await tx.vehicleStatus.findFirstOrThrow({
            where: { code: "AVAILABLE", active: true },
          });
          const equipmentStatus = await tx.equipmentStatus.findFirstOrThrow({
            where: { active: true },
          });
          const client = await tx.client.create({
            data: {
              code: namespace,
              name: `Workflow center ${namespace}`,
              stateId: state.id,
            },
          });
          const line = await tx.line.create({
            data: { name: `Workflow line ${namespace}`, clientId: client.id },
          });
          const equipment = await tx.equipment.create({
            data: {
              name: `Workflow sensor ${namespace}`,
              lineId: line.id,
              statusId: equipmentStatus.id,
            },
          });
          const actors = {} as Record<WorkflowRole, WorkflowActor>;
          const password = `Workflow-${randomUUID()}`;
          const hash = await bcrypt.hash(password, 4);
          for (const [key, code] of Object.entries(roleCodes)) {
            const role = await tx.role.findUniqueOrThrow({ where: { code } });
            if (role.isSuperuser)
              throw new Error("Workflow actors may not hold ROOT.");
            const user = await tx.user.create({
              data: {
                name: `Workflow ${key} ${namespace}`,
                email: `${key}-${namespace}@example.invalid`,
                password: hash,
                hireDate: new Date(
                  `${Number(today.slice(0, 4)) - 3}-01-01T06:00:00Z`,
                ),
                userStatusId: userStatus.id,
                userRoles: { create: { roleId: role.id } },
                clientAssignments: {
                  create: { clientId: client.id, isPrimary: true },
                },
              },
            });
            actors[key as WorkflowRole] = {
              id: user.id,
              name: user.name,
              email: user.email,
              password,
            };
          }
          const vehicles = [];
          for (const [index, actor] of [actors.fsrB, actors.fsrC].entries()) {
            vehicles.push(
              await tx.vehicle.create({
                data: {
                  make: "Workflow",
                  model: `Car ${index + 1}`,
                  year: Number(today.slice(0, 4)),
                  licensePlate: `W${index}${randomUUID().slice(0, 6)}`,
                  statusId: vehicleStatus.id,
                  assignedFsrId: actor.id,
                },
              }),
            );
          }
          const holidayDay = addCivilDays(today, 180);
          const syntheticHoliday = await tx.holiday.create({
            data: {
              name: `Workflow holiday ${namespace}`,
              month: Number(holidayDay.slice(5, 7)),
              day: Number(holidayDay.slice(8, 10)),
              year: Number(holidayDay.slice(0, 4)),
              isRecurring: false,
            },
          });
          const calendar = [
            ...holidays.map((rule) =>
              matching.some((row) => row.id === rule.id)
                ? { ...rule, active: false }
                : rule,
            ),
            syntheticHoliday,
          ];
          return {
            namespace,
            today,
            client,
            line,
            equipment,
            actors,
            vehicles,
            holidays: calendar,
            range: (offset: number, days: number) =>
              chargeableRange(addCivilDays(today, offset), days, calendar),
            assertSameDay: () => {
              if (mxDateString(new Date()) !== today)
                throw new Error(
                  `CDMX midnight crossed after workflow setup (${today}); rerun with fresh prerequisites.`,
                );
            },
          };
        },
        { timeout: 30_000 },
      );
      await use(world);
      world.assertSameDay();
    } finally {
      try {
        // Restore shared prerequisite flags even when setup or browser work fails.
        await prisma.$transaction(
          async (tx) => {
            for (const row of matching)
              await tx.holiday.update({
                where: { id: row.id },
                data: { active: row.active },
              });
            await tx.holiday.deleteMany({
              where: { name: `Workflow holiday ${namespace}` },
            });
            await tx.vacationSetting.update({
              where: { id: 1 },
              data: { graceWindowMonths: setting.graceWindowMonths },
            });
          },
          { timeout: 30_000 },
        );
        // Commit calendar restoration independently: a later FK cleanup failure
        // must not roll back the restored shared prerequisite flags.
        await prisma.$transaction(
          async (tx) => {
            if (!world) return;
            const userIds = Object.values(world.actors).map(
              (actor) => actor.id,
            );
            const incidents = await tx.incident.findMany({
              where: { clientId: world.client.id },
              select: { id: true },
            });
            const incidentIds = incidents.map((row) => row.id);
            const assignments = await tx.assignment.findMany({
              where: { incidentId: { in: incidentIds } },
              select: { id: true },
            });
            const assignmentIds = assignments.map((row) => row.id);
            // Test-owned cleanup is the only raw business-record write in this fixture.
            await tx.vehicleTrip.deleteMany({
              where: { fsrId: { in: userIds } },
            });
            await tx.assignmentActivity.deleteMany({
              where: { assignmentId: { in: assignmentIds } },
            });
            await tx.assignmentAttachment.deleteMany({
              where: { assignmentId: { in: assignmentIds } },
            });
            await tx.assignmentItem.deleteMany({
              where: { assignmentId: { in: assignmentIds } },
            });
            await tx.assignmentAssignee.deleteMany({
              where: { assignmentId: { in: assignmentIds } },
            });
            await tx.assignment.deleteMany({
              where: { id: { in: assignmentIds } },
            });
            await tx.incidentAttachment.deleteMany({
              where: { incidentId: { in: incidentIds } },
            });
            await tx.incident.deleteMany({
              where: { id: { in: incidentIds } },
            });
            await tx.schedule.deleteMany({
              where: { title: { contains: namespace } },
            });
            await tx.vacation.deleteMany({
              where: { userId: { in: userIds } },
            });
            await tx.vehicle.deleteMany({
              where: { id: { in: world.vehicles.map((row) => row.id) } },
            });
            await tx.user.deleteMany({ where: { id: { in: userIds } } });
            await tx.equipment.deleteMany({ where: { lineId: world.line.id } });
            await tx.line.delete({ where: { id: world.line.id } });
            await tx.client.delete({ where: { id: world.client.id } });
          },
          { timeout: 30_000 },
        );
      } finally {
        await disconnectDb();
      }
    }
  },
});
